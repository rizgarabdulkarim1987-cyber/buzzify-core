const place = (w: World, branch: 1 | 2 = 1) => ({ restaurantId: w.a.id, branchId: branch === 1 ? w.b1 : w.b2 });

/** The catalog the invoices are about: one product per distinct printed line (name, strength, form, pack), one unit each. */
type Catalog = Map<string, { productId: string; unitId: string }>;
const lineKey = (l: { name: string; strength: string | null; form: string | null; pack: string | null }) => [l.name, l.strength ?? '', l.form ?? '', l.pack ?? ''].join('\u0001');
const unitSize = (pack: string | null) => {
  const m = /^(\d+) (.+)$/.exec(pack ?? '');
  return m ? Number(m[1]) : 1;
};

async function seedCatalog(restaurantId: string): Promise<Catalog> {
  const catalog: Catalog = new Map();
  for (const inv of INVOICES) {
    for (const l of inv.lines) {
      const k = lineKey(l);
      if (catalog.has(k)) continue;
      // "10 tablets" is a top unit of 10 "tablets" over a piece, so the invoice's pack text names it exactly and the pipeline matches it by itself;
      // any other pack is one unit of 1, which the pipeline cannot match by identity: a person chooses it.
      const m = /^(\d+) (.+)$/.exec(l.pack ?? '');
      const baseQty = m ? Number(m[1]) : 1;
      const label = m ? m[2]! : (l.pack ?? 'pack');
      const made = await prisma().phProduct.create({
        data: {
          restaurantId,
          tradeName: l.name,
          strength: l.strength ?? '',
          form: l.form ?? '',
          identityKey: identityKeyOf({ tradeName: l.name, strength: l.strength ?? '', form: l.form ?? '', manufacturer: '', packLabel: `${baseQty} ${label}` }),
          searchText: searchTextOf({ tradeName: l.name, genericName: '', activeIngredient: '', strength: l.strength ?? '', form: l.form ?? '', manufacturer: '' }),
          units: { create: m ? [{ level: 0, label: 'piece', baseQty: 1 }, { level: 1, label, baseQty }] : [{ level: 0, label, baseQty }] },
        },
        select: { id: true, units: { select: { id: true }, orderBy: { level: 'desc' } } },
      });
      catalog.set(k, { productId: made.id, unitId: made.units[0]!.id });
    }
  }
  return catalog;
}

const getBatch = async (w: World, who: Person, batchId: string, branch: 1 | 2 = 1) => dataOf(await ask(who, reviewQueries.batchGet, { ...place(w, branch), batchId })) as unknown as BatchRead;
const live = (read: BatchRead) => read.rows.filter((r) => !r.removed);

/** Starts a batch for the invoice's supplier, uploads the page and (unless told not to) scripts the model's answer for it. */
async function upload(w: World, inv: SyntheticInvoice, o: { answer?: Parameters<ScriptedProvider['set']>[1]; noScript?: boolean } = {}) {
  const batchId = dataOf(await act(w.pic, intakeActions.createBatch, { ...place(w), clientKey: key(), supplierId: w.suppliers.get(inv.supplierName) })).id;
  const bytes = await renderInvoicePng(inv);
  const added = dataOf(await act(w.pic, intakeActions.addFile, { ...place(w), batchId, base64: bytes.toString('base64') }));
  if (!o.noScript) provider.set(sha(bytes), o.answer ?? textOf(inv));
  return { inv, batchId, fileId: added.fileId, uploaded: added.status, sha256: sha(bytes) };
}
const readFile = (w: World, fileId: string, def: typeof intakeActions.extract = intakeActions.extract) => act(w.pic, def, { ...place(w), fileId });

/** A person picks the product of every line the pipeline did not match by itself (the pipeline never picks between doubts). */
async function matchByHand(w: World, catalog: Catalog, inv: SyntheticInvoice, batchId: string): Promise<number> {
  const read = await getBatch(w, w.pic, batchId);
  const lines = truthLines(inv);
  let chosen = 0;
  for (const [i, row] of live(read).entries()) {
    if (row.matchState === 'MATCHED') continue;
    const target = catalog.get(lineKey(lines[i]!))!;
    dataOf(await act(w.pic, reviewActions.rowMatch, { ...place(w), rowId: row.id, version: row.version, productId: target.productId, unitId: target.unitId }));
    chosen += 1;
  }
  return chosen;
}

async function approveNow(w: World, batchId: string) {
  const read = await getBatch(w, w.pic, batchId);
  return act(w.pic, approveActions.approve, { ...place(w), batchId, clientKey: key(), expectedVersion: read.batch.version, verdictToken: read.verdictToken });
}

/** Acknowledges a line the way the screen does: the flags it showed, a note, and a reason for a printed total that does not add up. */
async function acknowledgeRow(w: World, batchId: string, index: number, mismatch: boolean) {
  const row = live(await getBatch(w, w.pic, batchId))[index]!;
  return act(w.pic, reviewActions.rowReview, {
    ...place(w),
    rowId: row.id,
    version: row.version,
    shown: row.flags,
    note: 'checked against the paper',
    ...(mismatch ? { mismatchReason: 'the printed total is wrong on the paper' } : {}),
  });
}

function percentile(values: number[], p: number): number {
  const sorted = [...values].sort((x, y) => x - y);
  return sorted[Math.min(sorted.length - 1, Math.ceil(sorted.length * p) - 1)]!;
}
